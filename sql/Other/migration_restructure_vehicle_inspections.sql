-- =============================================================================
-- Migration: Restructure vehicle_inspections into parent + two child tables
-- Relocate pre_diagnostics as child of vehicle_inspections
-- =============================================================================
-- Run this in Supabase SQL Editor (Query tab).
-- Safe to run on dummy/seed data — all existing data is migrated before
-- the old columns/FK are dropped.
-- =============================================================================

BEGIN;

-- Step 1: Create finding_status ENUM
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'finding_status') THEN
        CREATE TYPE finding_status AS ENUM ('ok', 'needs_attention', 'urgent');
    END IF;
END
$$;


-- Step 2: Add new timing columns to vehicle_inspections
ALTER TABLE vehicle_inspections
    ADD COLUMN IF NOT EXISTS started_at  TIMESTAMP,
    ADD COLUMN IF NOT EXISTS fulfilled_at TIMESTAMP;

-- Backfill started_at for existing rows using logged_date of earliest finding
UPDATE vehicle_inspections vi
SET started_at = COALESCE(
    (SELECT MIN(vi2.logged_date)
     FROM vehicle_inspections vi2
     WHERE vi2.job_order_id = vi.job_order_id),
    NOW()
)
WHERE vi.started_at IS NULL;


-- Step 3: Consolidate vehicle_inspections to one row per job order
-- We need to deduplicate: the OLD schema stored one row per finding/photo.
-- We keep the earliest row per job_order_id as the parent, delete the rest.
-- (The findings/photos will be re-inserted into the child tables below.)

-- First, create a helper temp table of which row ID is the "keeper" per job order
CREATE TEMP TABLE _vi_keepers AS
    SELECT DISTINCT ON (job_order_id) id AS keeper_id, job_order_id
    FROM vehicle_inspections
    ORDER BY job_order_id, id ASC;

-- Delete all non-keeper rows (findings data will be re-read from the full table backup)
CREATE TEMP TABLE _vi_backup AS SELECT * FROM vehicle_inspections;

DELETE FROM vehicle_inspections
WHERE id NOT IN (SELECT keeper_id FROM _vi_keepers);

-- Remove now-irrelevant old columns from the keeper rows
ALTER TABLE vehicle_inspections
    DROP COLUMN IF EXISTS name,
    DROP COLUMN IF EXISTS notes,
    DROP COLUMN IF EXISTS status,
    DROP COLUMN IF EXISTS photo,
    DROP COLUMN IF EXISTS findings_description,
    DROP COLUMN IF EXISTS logged_date;


-- Step 4: Create inspection_findings table
CREATE TABLE IF NOT EXISTS inspection_findings (
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inspection_id INT NOT NULL REFERENCES vehicle_inspections(id) DEFERRABLE INITIALLY IMMEDIATE,
    name          VARCHAR(100),
    description   TEXT,
    status        finding_status DEFAULT 'ok',
    photo         TEXT,
    logged_at     TIMESTAMP
);

-- Migrate findings from backup (rows where status != 'reference-photo')
INSERT INTO inspection_findings (inspection_id, name, description, status, photo, logged_at)
SELECT
    k.keeper_id,
    b.name,
    b.findings_description,
    CASE
        WHEN b.status = 'needs-attention' THEN 'needs_attention'::finding_status
        WHEN b.status = 'urgent'          THEN 'urgent'::finding_status
        ELSE                                   'ok'::finding_status
    END,
    b.photo,
    COALESCE(b.logged_date, NOW())
FROM _vi_backup b
JOIN _vi_keepers k ON k.job_order_id = b.job_order_id
WHERE (b.status IS NULL OR b.status NOT IN ('reference-photo'))
  AND (b.name IS NOT NULL OR b.findings_description IS NOT NULL);


-- Step 5: Create inspection_photos table
CREATE TABLE IF NOT EXISTS inspection_photos (
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inspection_id INT NOT NULL REFERENCES vehicle_inspections(id) DEFERRABLE INITIALLY IMMEDIATE,
    title         VARCHAR(100),
    note          TEXT,
    photo_url     TEXT,
    logged_at     TIMESTAMP
);

-- Migrate photos from backup (rows where status = 'reference-photo')
INSERT INTO inspection_photos (inspection_id, title, note, photo_url, logged_at)
SELECT
    k.keeper_id,
    b.name,
    b.notes,
    b.photo,
    COALESCE(b.logged_date, NOW())
FROM _vi_backup b
JOIN _vi_keepers k ON k.job_order_id = b.job_order_id
WHERE b.status = 'reference-photo'
  AND b.photo IS NOT NULL;


-- Step 6: Relocate pre_diagnostics from job_orders to vehicle_inspections
ALTER TABLE pre_diagnostics
    ADD COLUMN IF NOT EXISTS inspection_id INT;

-- Populate inspection_id by matching job_order_id through vehicle_inspections
UPDATE pre_diagnostics pd
SET inspection_id = vi.id
FROM vehicle_inspections vi
WHERE vi.job_order_id = pd.job_order_id
  AND pd.inspection_id IS NULL;

-- For any pre_diagnostics rows whose job_order didn't have an inspection yet,
-- create the inspection header row now
INSERT INTO vehicle_inspections (job_order_id, started_at)
SELECT DISTINCT pd.job_order_id, pd.datetime_created
FROM pre_diagnostics pd
WHERE pd.inspection_id IS NULL
  AND pd.job_order_id IS NOT NULL
  AND NOT EXISTS (
      SELECT 1 FROM vehicle_inspections vi WHERE vi.job_order_id = pd.job_order_id
  );

-- Re-try populating inspection_id for any remaining nulls
UPDATE pre_diagnostics pd
SET inspection_id = vi.id
FROM vehicle_inspections vi
WHERE vi.job_order_id = pd.job_order_id
  AND pd.inspection_id IS NULL;

-- Add FK constraint from pre_diagnostics.inspection_id → vehicle_inspections.id
ALTER TABLE pre_diagnostics
    ADD CONSTRAINT fk_pre_diagnostics_inspection
    FOREIGN KEY (inspection_id) REFERENCES vehicle_inspections(id) DEFERRABLE INITIALLY IMMEDIATE;

-- Drop the old job_order_id FK and column from pre_diagnostics
ALTER TABLE pre_diagnostics
    DROP CONSTRAINT IF EXISTS pre_diagnostics_job_order_id_fkey,
    DROP COLUMN IF EXISTS job_order_id;


-- Step 7: Drop/recreate stored functions to use new schema

DROP FUNCTION IF EXISTS get_inspection_findings(INT);
DROP FUNCTION IF EXISTS add_inspection_finding(INT, VARCHAR, TEXT, VARCHAR, TEXT, TEXT);

CREATE OR REPLACE FUNCTION get_inspection_findings(p_job_order_id INT)
RETURNS TABLE (
    id          INT,
    name        VARCHAR(100),
    description TEXT,
    status      finding_status,
    photo       TEXT,
    logged_at   TIMESTAMP
)
LANGUAGE SQL STABLE
AS $$
    SELECT f.id, f.name, f.description, f.status, f.photo, f.logged_at
    FROM inspection_findings f
    JOIN vehicle_inspections vi ON vi.id = f.inspection_id
    WHERE vi.job_order_id = p_job_order_id
    ORDER BY f.logged_at ASC;
$$;

CREATE OR REPLACE FUNCTION get_inspection_photos(p_job_order_id INT)
RETURNS TABLE (
    id        INT,
    title     VARCHAR(100),
    note      TEXT,
    photo_url TEXT,
    logged_at TIMESTAMP
)
LANGUAGE SQL STABLE
AS $$
    SELECT p.id, p.title, p.note, p.photo_url, p.logged_at
    FROM inspection_photos p
    JOIN vehicle_inspections vi ON vi.id = p.inspection_id
    WHERE vi.job_order_id = p_job_order_id
    ORDER BY p.logged_at ASC;
$$;

CREATE OR REPLACE FUNCTION get_or_create_inspection(p_job_order_id INT)
RETURNS TABLE (id INT, job_order_id INT, started_at TIMESTAMP, fulfilled_at TIMESTAMP)
LANGUAGE plpgsql VOLATILE
AS $$
DECLARE v_id INT;
BEGIN
    SELECT vi.id INTO v_id FROM vehicle_inspections vi WHERE vi.job_order_id = p_job_order_id LIMIT 1;
    IF v_id IS NULL THEN
        INSERT INTO vehicle_inspections (job_order_id, started_at)
        VALUES (p_job_order_id, NOW())
        RETURNING vehicle_inspections.id INTO v_id;
    END IF;
    RETURN QUERY SELECT vi.id, vi.job_order_id, vi.started_at, vi.fulfilled_at
    FROM vehicle_inspections vi WHERE vi.id = v_id;
END;
$$;

CREATE OR REPLACE FUNCTION complete_inspection(p_job_order_id INT)
RETURNS VOID LANGUAGE SQL VOLATILE AS $$
    UPDATE vehicle_inspections SET fulfilled_at = NOW()
    WHERE job_order_id = p_job_order_id AND fulfilled_at IS NULL;
$$;

CREATE OR REPLACE FUNCTION add_inspection_finding(
    p_job_order_id INT,
    p_name         VARCHAR(100),
    p_description  TEXT,
    p_status       finding_status,
    p_photo        TEXT
)
RETURNS TABLE (
    id            INT,
    inspection_id INT,
    name          VARCHAR(100),
    description   TEXT,
    status        finding_status,
    photo         TEXT,
    logged_at     TIMESTAMP
)
LANGUAGE plpgsql VOLATILE
AS $$
DECLARE
    v_inspection_id INT;
BEGIN
    SELECT vi.id INTO v_inspection_id
    FROM vehicle_inspections vi
    WHERE vi.job_order_id = p_job_order_id
    LIMIT 1;

    IF v_inspection_id IS NULL THEN
        INSERT INTO vehicle_inspections (job_order_id, started_at)
        VALUES (p_job_order_id, NOW())
        RETURNING vehicle_inspections.id INTO v_inspection_id;
    END IF;

    RETURN QUERY
    INSERT INTO inspection_findings (inspection_id, name, description, status, photo, logged_at)
    VALUES (v_inspection_id, p_name, p_description, p_status, p_photo, NOW())
    RETURNING
        inspection_findings.id,
        inspection_findings.inspection_id,
        inspection_findings.name,
        inspection_findings.description,
        inspection_findings.status,
        inspection_findings.photo,
        inspection_findings.logged_at;
END;
$$;

DROP FUNCTION IF EXISTS get_pre_diagnostic(INT);

CREATE OR REPLACE FUNCTION get_pre_diagnostic(p_job_order_id INT)
RETURNS TABLE (
    id                        INT,
    inspection_id             INT,
    mechanic_notes            TEXT,
    customer_approval_status  approval_status,
    datetime_created          TIMESTAMP,
    datetime_approved         TIMESTAMP
)
LANGUAGE SQL STABLE
AS $$
    SELECT pd.id, pd.inspection_id, pd.mechanic_notes,
           pd.customer_approval_status, pd.datetime_created, pd.datetime_approved
    FROM pre_diagnostics pd
    JOIN vehicle_inspections vi ON vi.id = pd.inspection_id
    WHERE vi.job_order_id = p_job_order_id
    ORDER BY pd.datetime_created DESC;
$$;

CREATE OR REPLACE FUNCTION get_job_order_inspections(p_job_order_id integer)
RETURNS TABLE (
    id INTEGER, name VARCHAR, status VARCHAR, photo TEXT, findings_description TEXT, logged_date TEXT
)
LANGUAGE sql STABLE
AS $$
    SELECT f.id, f.name, f.status::text, f.photo, f.description, f.logged_at::text
    FROM inspection_findings f
    JOIN vehicle_inspections vi ON vi.id = f.inspection_id
    WHERE vi.job_order_id = p_job_order_id
    ORDER BY f.logged_at ASC;
$$;

CREATE OR REPLACE FUNCTION advance_job_order_stage(
    p_job_order_id INT,
    p_new_status   job_orders_status
)
RETURNS VOID
LANGUAGE plpgsql VOLATILE
AS $$
DECLARE
    v_old_status job_orders_status;
BEGIN
    SELECT status INTO v_old_status
    FROM job_orders
    WHERE id = p_job_order_id;

    UPDATE job_orders
    SET status       = p_new_status,
        started_at   = CASE WHEN p_new_status = 'in_progress' AND started_at IS NULL THEN NOW() ELSE started_at END,
        completed_at = CASE WHEN p_new_status = 'completed' THEN NOW() ELSE completed_at END,
        released_at  = CASE WHEN p_new_status = 'released'  THEN NOW() ELSE released_at  END
    WHERE id = p_job_order_id;

    IF p_new_status = 'inspecting' THEN
        IF NOT EXISTS (SELECT 1 FROM vehicle_inspections WHERE job_order_id = p_job_order_id) THEN
            INSERT INTO vehicle_inspections (job_order_id, started_at)
            VALUES (p_job_order_id, NOW());
        END IF;
    END IF;

    IF v_old_status = 'inspecting' AND p_new_status <> 'inspecting' THEN
        UPDATE vehicle_inspections
        SET fulfilled_at = NOW()
        WHERE job_order_id = p_job_order_id AND fulfilled_at IS NULL;
    END IF;

    INSERT INTO system_audit_logs (
        user_id, employees_id, action_performed,
        entity_type, entity_id, old_values, new_values, action_date
    ) VALUES (
        NULL, NULL, 'status_changed',
        'job_orders', p_job_order_id,
        json_build_object('status', v_old_status::TEXT)::TEXT,
        json_build_object('status', p_new_status::TEXT)::TEXT,
        NOW()
    );
END;
$$;

-- Step 8: Clean up temp tables
DROP TABLE IF EXISTS _vi_backup;
DROP TABLE IF EXISTS _vi_keepers;

COMMIT;

