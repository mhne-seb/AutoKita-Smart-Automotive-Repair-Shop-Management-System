// scripts/migrate_retention_offers.js
// Migration script to restore promo_offer_type enum, retention_offers table,
// and seed initial demo retention offers into Supabase PostgreSQL.

const { Pool } = require('pg');
const fs = require('fs');
const path = require('path');
require('dotenv').config({ path: path.join(__dirname, '..', '.env.local') });

const pool = new Pool({
  host: process.env.DB_HOST,
  user: process.env.DB_USER,
  password: process.env.DB_PASSWORD,
  database: process.env.DB_NAME,
  port: parseInt(process.env.DB_PORT || '5432', 10),
  ssl: {
    rejectUnauthorized: true,
    ca: fs.readFileSync(path.join(__dirname, '..', 'certs', 'prod-ca-2021.crt')).toString(),
  },
});

async function migrate() {
  const client = await pool.connect();
  try {
    console.log('Connecting to database...');
    await client.query('BEGIN');

    // 1. Create Enum
    console.log('1. Ensuring promo_offer_type enum exists...');
    await client.query(`
      DO $$
      BEGIN
        IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'promo_offer_type') THEN
          CREATE TYPE promo_offer_type AS ENUM (
            'percentage_discount',
            'fixed_discount',
            'free_service',
            'service_reminder',
            'loyalty_reward'
          );
        END IF;
      END $$;
    `);

    // 2. Create Table
    console.log('2. Ensuring retention_offers table exists...');
    await client.query(`
      CREATE TABLE IF NOT EXISTS retention_offers (
        id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INT REFERENCES users (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
        promo_code VARCHAR UNIQUE,
        offer_type promo_offer_type,
        discount_value DECIMAL(10,2),
        description TEXT,
        issue_date DATE DEFAULT CURRENT_DATE,
        expiration_date DATE,
        is_claimed BOOLEAN DEFAULT FALSE,
        claimed_on_job_order_id INT REFERENCES job_orders (id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE
      );
    `);

    // 3. Comments and Indexes
    console.log('3. Creating indexes and comments...');
    await client.query(`
      COMMENT ON COLUMN retention_offers.promo_code IS 'e.g., COMEBACK15 or FREECHECK';
      COMMENT ON COLUMN retention_offers.claimed_on_job_order_id IS 'Tracks exactly which job order the promo was used on';
      CREATE INDEX IF NOT EXISTS idx_retention_offers_user_id ON retention_offers(user_id);
      CREATE INDEX IF NOT EXISTS idx_retention_offers_promo_code ON retention_offers(promo_code);
      CREATE INDEX IF NOT EXISTS idx_retention_offers_is_claimed ON retention_offers(is_claimed);
    `);

    // 4. Check if seed rows are needed
    const countRes = await client.query('SELECT COUNT(*) FROM retention_offers');
    const existingCount = parseInt(countRes.rows[0].count, 10);
    console.log(`Current retention_offers count: ${existingCount}`);

    if (existingCount === 0) {
      console.log('4. Seeding initial retention offers...');
      // Seed retention offers for customer users, including active offers for user 280
      await client.query(`
        INSERT INTO retention_offers (
          user_id,
          promo_code,
          offer_type,
          discount_value,
          description,
          issue_date,
          expiration_date,
          is_claimed,
          claimed_on_job_order_id
        )
        SELECT 
          u_id AS user_id,
          promo_code,
          o_type AS offer_type,
          discount_val AS discount_value,
          description,
          issue_date,
          expiration_date,
          CASE WHEN possible_jo_id IS NOT NULL THEN TRUE ELSE FALSE END AS is_claimed,
          possible_jo_id AS claimed_on_job_order_id
        FROM (
          SELECT
            u_id,
            o_type,
            CASE WHEN o_type = 'service_reminder' THEN NULL ELSE CONCAT(
              CASE o_type
                WHEN 'percentage_discount' THEN 'PCT'
                WHEN 'fixed_discount' THEN 'FIX'
                WHEN 'free_service' THEN 'FREE'
                WHEN 'loyalty_reward' THEN 'VIP'
              END,
              '-', n, '-', UPPER(SUBSTRING(MD5(RANDOM()::TEXT) FROM 1 FOR 4))
            ) END AS promo_code,
            CASE o_type
              WHEN 'percentage_discount' THEN ROUND((10 + (RANDOM() * 15))::NUMERIC, 2)
              WHEN 'fixed_discount' THEN ROUND((500 + (RANDOM() * 1500))::NUMERIC, 2)
              ELSE 0.00
            END AS discount_val,
            CASE o_type
              WHEN 'percentage_discount' THEN 'Enjoy a percentage off your total bill on your next visit.'
              WHEN 'fixed_discount' THEN 'Use this voucher to get a fixed amount deducted from your total cost.'
              WHEN 'free_service' THEN 'Come in for a complimentary multipoint vehicle inspection.'
              WHEN 'service_reminder' THEN 'Friendly reminder: Your vehicle is due for its periodic maintenance.'
              WHEN 'loyalty_reward' THEN 'Thank you for your continued trust! Enjoy this exclusive loyalty reward.'
            END AS description,
            issue_dt AS issue_date,
            issue_dt + INTERVAL '60 days' AS expiration_date,
            CASE WHEN claim_roll > 0.7 THEN
              (SELECT id FROM job_orders WHERE user_id = u_id AND status IN ('completed', 'released') ORDER BY RANDOM() LIMIT 1)
            ELSE NULL
            END AS possible_jo_id
          FROM (
            SELECT 
              n,
              u.id AS u_id,
              (ARRAY['percentage_discount', 'fixed_discount', 'free_service', 'service_reminder', 'loyalty_reward'])[1 + FLOOR(RANDOM() * 5)::INT]::promo_offer_type AS o_type,
              (CURRENT_DATE - (FLOOR(RANDOM() * 60)::INT || ' days')::INTERVAL)::DATE AS issue_dt,
              RANDOM() AS claim_roll
            FROM GENERATE_SERIES(1, 150) AS loop(n)
            CROSS JOIN LATERAL (
              SELECT id
              FROM users
              WHERE role = 'customer' OR role = 'c' OR role LIKE 'c%'
              ORDER BY RANDOM()
              LIMIT 1
            ) AS u
          ) AS raw_data
        ) AS processed_data;
      `);

      // Explicitly guarantee active offers for demo user 280
      await client.query(`
        INSERT INTO retention_offers (
          user_id, promo_code, offer_type, discount_value, description, issue_date, expiration_date, is_claimed
        )
        VALUES 
          (280, 'COMEBACK15', 'percentage_discount', 15.00, 'Special 15% discount on your next periodic maintenance service.', CURRENT_DATE, CURRENT_DATE + INTERVAL '30 days', false),
          (280, 'FREECHECK', 'free_service', 0.00, 'Complimentary 25-Point Computerized Diagnostic & Safety Check.', CURRENT_DATE, CURRENT_DATE + INTERVAL '45 days', false)
        ON CONFLICT (promo_code) DO NOTHING;
      `);
    }

    await client.query('COMMIT');
    const finalCount = await client.query('SELECT COUNT(*) FROM retention_offers');
    console.log(`✓ Migration complete! Total retention_offers in Supabase: ${finalCount.rows[0].count}`);
  } catch (err) {
    await client.query('ROLLBACK');
    console.error('Migration failed:', err);
    process.exit(1);
  } finally {
    client.release();
    await pool.end();
  }
}

migrate();
